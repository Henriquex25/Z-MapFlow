package keymap

import (
	"fmt"
	"strconv"
	"strings"
	"z-mapflow/internal/models"
)

// ImportConfig consumes fields the editor owns, retaining all other Kconfig.
// Generated queue sizes are recalculated rather than freezing an old estimate.
func ImportConfig(source string, p models.Project) (models.Project, error) {
	var extra []string
	generated := strings.Contains(source, "# Generated by Z-MapFlow")
	for _, line := range strings.Split(source, "\n") {
		key, value, ok := strings.Cut(strings.TrimSpace(line), "=")
		if !ok || strings.HasPrefix(key, "#") {
			if !strings.HasPrefix(line, "# Generated by Z-MapFlow") {
				extra = append(extra, line)
			}
			continue
		}
		value = strings.TrimSpace(value)
		boolean := map[string]*bool{"CONFIG_ZMK_SLEEP": &p.Options.Sleep, "CONFIG_ZMK_DISPLAY": &p.Options.Display, "CONFIG_ZMK_POINTING": &p.Options.Pointing, "CONFIG_ZMK_RGB_UNDERGLOW": &p.Options.RGBUnderglow, "CONFIG_ZMK_BACKLIGHT": &p.Options.Backlight, "CONFIG_ZMK_PM_SOFT_OFF": &p.Options.SoftOff}
		if dest, known := boolean[key]; known {
			if value != "y" && value != "n" {
				return p, fmt.Errorf("valor Kconfig inválido em %s", key)
			}
			*dest = value == "y"
			continue
		}
		if key == "CONFIG_ZMK_IDLE_SLEEP_TIMEOUT" {
			n, e := strconv.Atoi(value)
			if e != nil {
				return p, e
			}
			p.Options.SleepTimeoutMs = n
			continue
		}
		if generated && (key == "CONFIG_ZMK_BEHAVIORS_QUEUE_SIZE" || key == "CONFIG_BT_MAX_CONN") {
			continue
		}
		if generated && key == "CONFIG_BT_MAX_PAIRED" {
			n, e := strconv.Atoi(value)
			if e != nil {
				return p, e
			}
			p.Options.BluetoothProfiles = n - 1
			continue
		}
		extra = append(extra, line)
	}
	p.ExtraConfig = strings.TrimSpace(strings.Join(extra, "\n"))
	return p, nil
}
