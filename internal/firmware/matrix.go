package firmware

import (
	"fmt"
	"gopkg.in/yaml.v3"
	"strings"
	"z-mapflow/internal/models"
	"z-mapflow/internal/project"
)

// Each argument is quoted independently for both the shell and the Actions
// build workflow. User flags must never become executable shell syntax.
func shellQuote(value string) string { return "'" + strings.ReplaceAll(value, "'", "'\"'\"'") + "'" }

func TargetBuildCommand(p models.Project, variant models.Variant, target models.Target) string {
	settings := project.TargetSettings(p, target.ID)
	args := []string{"west", "build", "-p", "always", "-s", "zmk/app", "-d", "build/" + variant.ID + "/" + target.ID, "-b", target.Board}
	for _, snippet := range settings.Snippets {
		args = append(args, "-S", snippet)
	}
	args = append(args, "--", "-DSHIELD="+target.Shield, "-DZMK_CONFIG=/workspace/config")
	args = append(args, settings.CMakeArgs...)
	for i, a := range args {
		args[i] = shellQuote(a)
	}
	return strings.Join(args, " ")
}
func GenerateBuildMatrix(p models.Project, plugin models.Plugin) (string, error) {
	variant, err := project.Variant(p, plugin)
	if err != nil {
		return "", err
	}
	type entry struct {
		Board    string `yaml:"board"`
		Shield   string `yaml:"shield,omitempty"`
		Snippet  string `yaml:"snippet,omitempty"`
		Args     string `yaml:"cmake-args,omitempty"`
		Artifact string `yaml:"artifact-name,omitempty"`
	}
	matrix := struct {
		Include []entry `yaml:"include"`
	}{}
	for _, target := range variant.Targets {
		settings := project.TargetSettings(p, target.ID)
		args := make([]string, len(settings.CMakeArgs))
		for i, a := range settings.CMakeArgs {
			args[i] = shellQuote(a)
		}
		matrix.Include = append(matrix.Include, entry{target.Board, target.Shield, strings.Join(settings.Snippets, " "), strings.Join(args, " "), strings.TrimSuffix(target.Artifact, ".uf2")})
	}
	data, err := yaml.Marshal(matrix)
	if err != nil {
		return "", fmt.Errorf("build.yaml: %w", err)
	}
	return "# Generated by Z-MapFlow. Place at the root of your zmk-config repository.\n" + string(data), nil
}
