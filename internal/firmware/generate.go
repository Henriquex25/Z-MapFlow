//go:embed keys_pt_abnt2.h
var abnt2Header string

type SourceFile struct {
	Name    string `json:"name"`
	Content string `json:"content"`
}

func Generate(p models.Project, r *devices.Registry) ([]SourceFile, error) {
	p = project.Migrate(p)
	if err := project.Validate(p, r); err != nil {
		return nil, err
	}
	d, _ := r.Get(p.PluginID)
	plugin := BuildProfile(p, d.Descriptor())
	resolve := func(s string) string {
		v, _ := project.Resolve(s, p.Layout.Layers)
		if strings.HasPrefix(strings.TrimSpace(v), "&") {
			if parts, e := project.BindingParts(v); e == nil {
				return strings.Join(parts, " ")
			}
		}
		return v
	}
	var keymap strings.Builder
	keymap.WriteString("// Generated by Z-MapFlow.\n")
	keymap.WriteString(p.Preamble)
	for _, header := range []string{"behaviors.dtsi", "dt-bindings/zmk/keys.h", "dt-bindings/zmk/bt.h", "dt-bindings/zmk/outputs.h", "dt-bindings/zmk/rgb.h", "dt-bindings/zmk/ext_power.h", "dt-bindings/zmk/pointing.h", "dt-bindings/zmk/modifiers.h", "dt-bindings/zmk/hid_usage_pages.h", "dt-bindings/zmk/backlight.h"} {
		if !strings.Contains(p.Preamble, "<"+header+">") && !strings.Contains(p.Preamble, strconv.Quote(header)) {
			fmt.Fprintf(&keymap, "\n#include <%s>\n", header)
		}
	}
	if len(p.Layout.InputProcessors) > 0 && !strings.Contains(p.Preamble, "input/processors.dtsi") {
		keymap.WriteString("#include <input/processors.dtsi>\n")
	}
	localized := p.Options.Locale == "pt-br"
	_ = project.EachBinding(p, func(code string) error {
		if strings.Contains(code, "PT_") {
			localized = true
		}
		return nil
	})
	if localized && !strings.Contains(p.Preamble, "keys_pt_abnt2.h") {
		keymap.WriteString("#include \"keys_pt_abnt2.h\"\n")
	}
	if strings.HasPrefix(p.Options.Locale, "header:") {
		name := strings.TrimPrefix(p.Options.Locale, "header:")
		if !strings.Contains(p.Preamble, strconv.Quote(name)) {
			fmt.Fprintf(&keymap, "#include %s\n", strconv.Quote(name))
		}
	}
	keymap.WriteString("\n/ {\n  behaviors {\n")
	for _, b := range p.Layout.Behaviors {
		if b.Target == "" {
			writeBehavior(&keymap, b, resolve)
		}
	}
	for li, l := range p.Layout.Layers {
		for si, s := range l.Sensors {
			if s.Inherited {
				continue
			}
			fmt.Fprintf(&keymap, "    zm_sensor_%d_%d: sensor_%d_%d {\n      compatible = \"zmk,behavior-sensor-rotate\";\n      #sensor-binding-cells = <0>;\n      bindings = <%s>, <%s>;\n", li, si, li, si, resolve(s.CodeCW), resolve(s.CodeCCW))
			if s.TapMs != nil {
				fmt.Fprintf(&keymap, "      tap-ms = <%d>;\n", *s.TapMs)
			}
			keymap.WriteString("    };\n")
		}
	}
	keymap.WriteString("  };\n")
	for _, b := range p.Layout.Behaviors {
		if b.Target == "" && (b.Kind == "mouse-move" || b.Kind == "mouse-scroll") {
			flat := strings.Join(strings.Fields(p.ExtraDTS), "")
			if !strings.Contains(flat, "device=<&"+b.ID+">") {
				fmt.Fprintf(&keymap, "  %s_listener: %s_listener { compatible = \"zmk,input-listener\"; device = <&%s>; };\n", b.ID, b.ID, b.ID)
			}
		}
	}
	if len(p.Layout.Macros) > 0 {
		keymap.WriteString("  macros {\n")
		for _, m := range p.Layout.Macros {
			compatible := "zmk,behavior-macro"
			if m.ParameterCount == 1 {
				compatible += "-one-param"
			}
			if m.ParameterCount == 2 {
				compatible += "-two-param"
			}
			fmt.Fprintf(&keymap, "    %s: %s {\n      compatible = %s;\n      #binding-cells = <%d>;\n      display-name = %s;\n      tap-ms = <%d>;\n      wait-ms = <%d>;\n      bindings = ", m.ID, m.ID, strconv.Quote(compatible), m.ParameterCount, strconv.Quote(m.Name), m.TapMs, m.WaitMs)
			bindings, _ := project.MacroBindings(m)
			for i, c := range bindings {
				if i > 0 {
					keymap.WriteString(", ")
				}
				fmt.Fprintf(&keymap, "<%s>", resolve(c))
			}
			keymap.WriteString(";\n    };\n")
		}
		keymap.WriteString("  };\n")
	}
	if len(p.Layout.Combos) > 0 {
		keymap.WriteString("  combos {\n    compatible = \"zmk,combos\";\n")
		for _, c := range p.Layout.Combos {
			fmt.Fprintf(&keymap, "    %s {\n      timeout-ms = <%d>;\n      key-positions = <", c.ID, c.TimeoutMs)
			for _, pos := range c.Positions {
				fmt.Fprintf(&keymap, "%d ", pos)
			}
			fmt.Fprintf(&keymap, ">;\n      bindings = <%s>;\n", resolve(c.Binding))
			if c.RequirePriorIdleMs != nil {
				fmt.Fprintf(&keymap, "      require-prior-idle-ms = <%s>;\n", numberCell(*c.RequirePriorIdleMs))
			}
			if len(c.LayerIDs) > 0 {
				keymap.WriteString("      layers = <")
				for _, id := range c.LayerIDs {
					fmt.Fprintf(&keymap, "%s ", resolve("@{"+id+"}"))
				}
				keymap.WriteString(">;\n")
			}
			if c.SlowRelease {
				keymap.WriteString("      slow-release;\n")
			}
			keymap.WriteString("    };\n")
		}
		keymap.WriteString("  };\n")
	}
	if len(p.Layout.ConditionalLayers) > 0 {
		keymap.WriteString("  conditional_layers {\n    compatible = \"zmk,conditional-layers\";\n")
		for _, c := range p.Layout.ConditionalLayers {
			fmt.Fprintf(&keymap, "    %s { if-layers = <", c.ID)
			for _, id := range c.IfLayerIDs {
				fmt.Fprintf(&keymap, "%s ", resolve("@{"+id+"}"))
			}
			fmt.Fprintf(&keymap, ">; then-layer = <%s>; };\n", resolve("@{"+c.ThenLayerID+"}"))
		}
		keymap.WriteString("  };\n")
	}
	keymap.WriteString("  keymap {\n    compatible = \"zmk,keymap\";\n")
	for li, l := range p.Layout.Layers {
		fmt.Fprintf(&keymap, "    layer_%d {\n      display-name = %s;\n      bindings = <\n", li, strconv.Quote(l.Name))
		keys := append([]models.KeyAction(nil), l.Keys...)
		sort.Slice(keys, func(i, j int) bool { return keys[i].KeymapIndex < keys[j].KeymapIndex })
		for i, k := range keys {
			if i%6 == 0 {
				keymap.WriteString("        ")
			}
			fmt.Fprintf(&keymap, "%s ", resolve(k.Code))
			if i%6 == 5 {
				keymap.WriteString("\n")
			}
		}
		keymap.WriteString("\n      >;\n")
		count := len(l.Sensors)
		for count > 0 && l.Sensors[count-1].Inherited {
			count--
		}
		if count > 0 {
			keymap.WriteString("      sensor-bindings = <")
			for si, sensor := range l.Sensors[:count] {
				if sensor.Inherited {
					keymap.WriteString("&trans ")
				} else {
					fmt.Fprintf(&keymap, "&zm_sensor_%d_%d ", li, si)
				}
			}
			keymap.WriteString(">;\n")
		}
		keymap.WriteString("    };\n")
	}
	keymap.WriteString("  };\n};\n\n")
	keymap.WriteString(plugin.Overlay)
	// Transparent behaviors lack sensor callbacks, so ZMK continues to the next
	// layer. Supply the sensor cell declaration for holes preceding other sensors.
	for _, l := range p.Layout.Layers {
		count := len(l.Sensors)
		for count > 0 && l.Sensors[count-1].Inherited {
			count--
		}
		for _, s := range l.Sensors[:count] {
			if s.Inherited && !strings.Contains(strings.Join(strings.Fields(p.ExtraDTS), ""), "&trans{#sensor-binding-cells=<0>;") {
				keymap.WriteString("\n&trans { #sensor-binding-cells = <0>; };\n")
				goto sensorsDone
			}
		}
	}
sensorsDone:
	for _, name := range []string{"mt", "lt"} {
		v := project.HoldTapOptions(p, name)
		fmt.Fprintf(&keymap, "\n&%s { tapping-term-ms = <%d>; quick-tap-ms = <%s>; flavor = %s; };\n", name, v.TappingTermMs, numberCell(v.QuickTapMs), strconv.Quote(v.Flavor))
	}
	for _, b := range p.Layout.Behaviors {
		if b.Target != "" {
			writeBehavior(&keymap, b, resolve)
		}
	}
	if len(p.Layout.Layers) > 0 {
		sensors := p.Layout.Layers[0].Sensors
		any := false
		for _, s := range sensors {
			any = any || s.TriggersPerRotation > 0
		}
		if any {
			keymap.WriteString("\n&sensors {\n")
			for i, s := range sensors {
				fmt.Fprintf(&keymap, "  sensor_config_%d {", i)
				if s.TriggersPerRotation > 0 {
					fmt.Fprintf(&keymap, " triggers-per-rotation = <%d>;", s.TriggersPerRotation)
				}
				keymap.WriteString(" };\n")
			}
			keymap.WriteString("};\n")
		}
	}
	listeners := []string{}
	for _, c := range p.Layout.InputProcessors {
		found := false
		for _, name := range listeners {
			found = found || name == c.Listener
		}
		if !found {
			listeners = append(listeners, c.Listener)
		}
	}
	for _, listener := range listeners {
		fmt.Fprintf(&keymap, "\n&%s {\n", listener)
		for _, c := range p.Layout.InputProcessors {
			if c.Listener != listener {
				continue
			}
			if len(c.LayerIDs) > 0 {
				fmt.Fprintf(&keymap, "  %s { layers = <", c.ID)
				for _, id := range c.LayerIDs {
					fmt.Fprintf(&keymap, "%s ", resolve("@{"+id+"}"))
				}
				keymap.WriteString(">;\n")
			}
			keymap.WriteString("    input-processors = <")
			for _, code := range c.Bindings {
				keymap.WriteString(resolve(code) + " ")
			}
			keymap.WriteString(">;\n")
			if len(c.LayerIDs) > 0 {
				if c.ProcessNext {
					keymap.WriteString("    process-next;\n")
				}
				keymap.WriteString("  };\n")
			}
		}
		keymap.WriteString("};\n")
	}
	keymap.WriteString("\n" + resolve(p.ExtraDTS) + "\n")
	yesno := func(b bool) string {
		if b {
			return "y"
		}
		return "n"
	}
	config := fmt.Sprintf("# Generated by Z-MapFlow\n%sCONFIG_ZMK_SLEEP=%s\nCONFIG_ZMK_IDLE_SLEEP_TIMEOUT=%d\nCONFIG_ZMK_DISPLAY=%s\nCONFIG_ZMK_POINTING=%s\n", plugin.Config, yesno(p.Options.Sleep), p.Options.SleepTimeoutMs, yesno(p.Options.Display), yesno(p.Options.Pointing))
	for _, capability := range plugin.Capabilities {
		if capability == "bluetooth" {
			config += fmt.Sprintf("CONFIG_BT_MAX_PAIRED=%d\nCONFIG_BT_MAX_CONN=%d\n", p.Options.BluetoothProfiles+1, p.Options.BluetoothProfiles+1)
		}
	}
	if p.Options.Display {
		config += "CONFIG_ZMK_DISPLAY_STATUS_SCREEN_BUILT_IN=y\nCONFIG_ZMK_WIDGET_LAYER_STATUS=y\nCONFIG_ZMK_WIDGET_BATTERY_STATUS=y\nCONFIG_ZMK_WIDGET_BATTERY_STATUS_SHOW_PERCENTAGE=y\nCONFIG_ZMK_WIDGET_OUTPUT_STATUS=y\nCONFIG_ZMK_DISPLAY_WORK_QUEUE_DEDICATED=y\n"
	}

	if p.Options.RGBUnderglow {
		config += "CONFIG_ZMK_RGB_UNDERGLOW=y\n"
	}
	if p.Options.Backlight {
		config += "CONFIG_ZMK_BACKLIGHT=y\n"
	}
	if p.Options.SoftOff {
		config += "CONFIG_ZMK_PM_SOFT_OFF=y\n"
	}
	config += fmt.Sprintf("CONFIG_ZMK_BEHAVIORS_QUEUE_SIZE=%d\n", project.MacroQueueSize(p))
	config += "\n" + p.ExtraConfig + "\n"
	manifest := fmt.Sprintf("manifest:\n  projects:\n    - name: zmk\n      url: https://github.com/zmkfirmware/zmk\n      revision: %s\n      import: app/west.yml\n", strconv.Quote(plugin.ZMKRevision))
	for _, module := range plugin.Modules {
		manifest += fmt.Sprintf("    - name: %s\n      url: %s\n      revision: %s\n      import: %t\n", strconv.Quote(module.Name), strconv.Quote(module.URL), strconv.Quote(module.Revision), module.Import)
	}
	manifest += "  self:\n    path: config\n"

	files := []SourceFile{{Name: plugin.KeymapName + ".keymap", Content: keymap.String()}, {Name: plugin.KeymapName + ".conf", Content: config}, {Name: "west.yml", Content: manifest}}
	if localized && p.Headers["keys_pt_abnt2.h"] == "" {
		files = append(files, SourceFile{Name: "keys_pt_abnt2.h", Content: abnt2Header})
	}
	headerNames := make([]string, 0, len(p.Headers))
	for name := range p.Headers {
		headerNames = append(headerNames, name)
	}
	sort.Strings(headerNames)
	for _, name := range headerNames {
		files = append(files, SourceFile{Name: name, Content: p.Headers[name]})
	}
	matrix, err := GenerateBuildMatrix(p, plugin)
	if err != nil {
		return nil, err
	}
	files = append(files, SourceFile{Name: "build.yaml", Content: matrix})
	names := make([]string, 0, len(plugin.Files))
	for name := range plugin.Files {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		files = append(files, SourceFile{Name: name, Content: plugin.Files[name]})
	}
	return files, nil
}

// BuildProfile resolves version-specific toolchains declared by the plugin.
func BuildProfile(p models.Project, plugin models.Plugin) models.Plugin {
	v, err := project.Variant(p, plugin)
	if err != nil {
		return plugin
	}
	if v.ZMKRevision != "" {
		plugin.ZMKRevision = v.ZMKRevision
	}
	if v.BuildImage != "" {
		plugin.BuildImage = v.BuildImage
	}
	return plugin
}
